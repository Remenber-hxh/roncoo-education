--      users_log        → 登录时间、IP、地域、浏览器、操作系统、登录方式
--      user_study_daily → 每日学习时长（秒）
--      user_certificate → 证书类型、证书编号、发证与到期日期、证书扫描件
--      user_agreement_sign → 签署时间、签署 IP
--      考试相关         → 答卷、得分、是否通过

--
-- 录入方式二选一：
--   A. 执行本脚本
--   B. 后台【系统管理 → 参数配置】找到「隐私政策」，点修改，用富文本编辑器粘贴

UPDATE sys_config SET config_value = '
<h3>一、本政策的适用范围</h3>
<p>本平台为公司内部员工培训系统，仅供在职员工及经授权的相关人员使用，不对外部公众开放。本政策说明平台在您使用过程中收集哪些信息、如何使用这些信息，以及您享有的权利。</p>

<h3>二、我们收集的信息</h3>
<p><strong>1. 账号与档案信息</strong><br/>
手机号、姓名、性别、出生日期、头像、工号、所属班组、岗位、入职日期。其中手机号用于登录，工号与班组用于统计培训完成情况。</p>

<p><strong>2. 学习记录</strong><br/>
课程学习进度、每日学习时长、图文课时的阅读进度与阅读时长、课程收藏与评论。</p>

<p><strong>3. 考核记录</strong><br/>
考试答卷、得分、是否通过、交卷时间、补考场次。</p>

<p><strong>4. 证书信息</strong><br/>
若您的岗位涉及持证要求，平台会记录证书类型、证书编号、发证日期、到期日期，并保存您上传的证书扫描件，用于到期前提醒换证。</p>

<p><strong>5. 协议签署记录</strong><br/>
您在平台上确认签署培训文件时，系统会记录签署时间与签署时的 IP 地址，作为完成培训的凭证。</p>

<p><strong>6. 登录日志</strong><br/>
登录时间、登录方式、IP 地址、由 IP 推断的大致地域、浏览器与操作系统类型。这些信息用于账号安全审计。</p>

<h3>三、信息的使用方式</h3>
<p>上述信息仅用于以下用途：</p>
<ul>
<li>开展员工培训、记录培训完成情况</li>
<li>统计部门与班组的培训进度，向管理者提供汇总数据</li>
<li>证书到期提醒</li>
<li>账号安全审计与异常登录排查</li>
</ul>
<p>我们不会将上述信息用于培训管理以外的目的，不会向公司外部的第三方出售、出租或共享您的个人信息，法律法规另有强制要求的除外。</p>

<h3>四、信息的查看范围</h3>
<p>您的学习记录与考核成绩，您本人、您的直属主管、培训管理员以及人力资源部门可以查看。平台管理员因系统维护需要可访问后台数据，相关操作会留有日志。</p>

<h3>五、信息的存储与保护</h3>
<p>数据存储于公司内部服务器。登录密码经加盐哈希后存储，平台不保存也无法还原您的明文密码。培训与考核记录在您离职后按公司档案管理规定保留。</p>

<h3>六、您的权利</h3>
<p>您可以在【个人中心】查看和修改本人的昵称、生日等资料。手机号、工号、班组等与身份和组织架构相关的信息由人力资源部门统一维护，如有错误请联系人力资源部门更正。对本政策或您的个人信息有疑问的，同样可联系人力资源部门。</p>

<h3>七、政策更新</h3>
<p>本政策如有修订，将在本页面更新。请留意查看。</p>
' WHERE config_key = 'websitePrivacyPolicy';

-- 校验
SELECT config_key, config_name, content_type,
       LENGTH(config_value) AS 正文长度,
       IF(LENGTH(config_value) > 0, '已录入', '仍为空') AS 状态
FROM sys_config WHERE config_key = 'websitePrivacyPolicy';
